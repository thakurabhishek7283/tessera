// Generates the configuration reference from the zod schema in @tessera/core, so the docs cannot
// drift from the validation that actually runs. Usage: `pnpm docs:gen` (needs `pnpm build` first).
import { mkdirSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import { TesseraConfigSchema } from '../packages/core/dist/index.js';

const schema = z.toJSONSchema(TesseraConfigSchema, {
  unrepresentable: 'any',
  io: 'input',
  target: 'draft-2020-12',
});

const outDir = new URL('../apps/docs/', import.meta.url);
mkdirSync(new URL('public/', outDir), { recursive: true });
mkdirSync(new URL('reference/', outDir), { recursive: true });

// Editors use this for autocomplete: { "$schema": "https://…/tessera-config.schema.json" }
writeFileSync(
  new URL('public/tessera-config.schema.json', outDir),
  `${JSON.stringify(schema, null, 2)}\n`,
);

/** @typedef {{ path: string, types: Set<string>, required: boolean, defaults: Set<string>, description: string }} Row */

function typeOf(node) {
  if ('const' in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  if (node.type === 'array') return `${node.items ? typeOf(node.items) : 'any'}[]`;
  if (
    node.type === 'object' &&
    node.additionalProperties &&
    typeof node.additionalProperties === 'object'
  ) {
    return `Record<string, ${typeOf(node.additionalProperties)}>`;
  }
  if (node.type) return Array.isArray(node.type) ? node.type.join(' \\| ') : node.type;
  if (node.anyOf || node.oneOf) {
    const parts = node.anyOf ?? node.oneOf;
    return parts.every((p) => p.type === 'object') ? 'object' : parts.map(typeOf).join(' \\| ');
  }
  return 'function / object';
}

/** @param {Map<string, Row>} rows */
function collect(node, path, requiredHere, rows, variant) {
  const variants = node.anyOf ?? node.oneOf;
  if (variants?.every((v) => v.type === 'object')) {
    for (const v of variants)
      collect(v, path, requiredHere, rows, v.properties?.type?.const ?? variant);
    return;
  }
  if (node.type !== 'object') return;
  const required = new Set(node.required ?? []);
  for (const [key, child] of Object.entries(node.properties ?? {})) {
    const childPath = path ? `${path}.${key}` : key;
    const row = rows.get(childPath) ?? {
      path: childPath,
      types: new Set(),
      required: required.has(key),
      defaults: new Set(),
      description: '',
      variants: new Set(),
    };
    row.types.add(typeOf(child));
    if (variant !== undefined && key !== 'type') row.variants.add(variant);
    if ('default' in child) row.defaults.add(JSON.stringify(child.default));
    row.description ||=
      child.description ??
      (key === 'type' && variant === undefined
        ? 'Selects which variant of this option to use.'
        : '');
    rows.set(childPath, row);
    collect(child, childPath, required.has(key), rows, variant);
  }
  if (node.additionalProperties && typeof node.additionalProperties === 'object') {
    collect(node.additionalProperties, `${path}.<key>`, false, rows, variant);
  }
}

const rows = new Map();
collect(schema, '', true, rows);

const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = [...rows.values()]
  .map((r) => {
    const type = [...r.types].join(' \\| ').replace(/ \\\| /g, ' \\| ');
    const dflt = r.defaults.size ? `\`${[...r.defaults].join(', ')}\`` : '—';
    const only = r.variants.size
      ? ` when \`type\` is ${[...r.variants].map((v) => `\`"${v}"\``).join(' or ')}`
      : '';
    const required = r.required ? `yes${only}` : only ? `no${only}` : 'no';
    return `| \`${r.path}\` | \`${type}\` | ${required} | ${dflt} | ${cell(r.description)} |`;
  })
  .join('\n');

const page = `---
outline: [2, 3]
---

<!-- Generated by scripts/gen-config-docs.mjs from the zod schema in @tessera/core. Do not edit. -->

# Configuration reference

\`createTessera(config, options)\` validates \`config\` against the schema below. A mistake fails fast with a readable message that names the path, for example \`features.kanban.columns: expected array\`.

\`\`\`ts
import { createTessera } from '@tessera/core';

const tessera = createTessera(
  {
    appId: 'my-app',
    features: { chat: { enabled: true } },
  },
  { plugins: { chat: () => import('@tessera/chat') }, adapters },
);
\`\`\`

## Instance options

| Option | Type | Required | Default | Description |
| --- | --- | --- | --- | --- |
${table}

Options that only apply to some variants say so in the *Required* column: choose the variant with the \`type\` field, for example \`transport.type\`.

## Editor autocomplete

A JSON Schema is published next to these docs. Point your JSON files at it:

\`\`\`json
{ "$schema": "./tessera-config.schema.json", "appId": "my-app", "features": {} }
\`\`\`

## Feature options

\`features.<id>\` is validated by the plugin that owns it when the feature is set up, and a failure is reported as \`features.<id>.<option>: …\`. Each kit documents its own options in its package README. Every plugin accepts \`{ "enabled": true }\` on its own: all other options have defaults.
`;
writeFileSync(new URL('reference/configuration.md', outDir), page);
console.log(`wrote ${rows.size} configuration rows`);
